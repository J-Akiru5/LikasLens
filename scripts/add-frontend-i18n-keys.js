// Add translations to all 9 locale files
const locales = ['fil', 'vi', 'id', 'ms', 'ta', 'th', 'km', 'my', 'lo'];
locales.forEach(loc => {
  const filePath = path.join(sharedDir, `${loc}.json`);
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  if (!data.dashboard) data.dashboard = {};
  
  let added = 0;
  const t = translations[loc];
  Object.entries(t).forEach(([k, v]) => {
    if (!data.dashboard[k]) {
      data.dashboard[k] = v;
      added++;
    }
  });
  
  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');
  console.log(`${loc}: added ${added} keys`);
});

console.log('\nDone! All translation keys added.');
