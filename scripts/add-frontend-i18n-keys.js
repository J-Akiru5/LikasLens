const en = JSON.parse(fs.readFileSync(enPath, 'utf8'));

// Add new keys to en.json dashboard namespace
if (!en.dashboard) en.dashboard = {};
let addedToEn = 0;
Object.entries(newDashboardKeys).forEach(([k, v]) => {
  if (!en.dashboard[k]) {
    en.dashboard[k] = v;
    addedToEn++;
  }
});
