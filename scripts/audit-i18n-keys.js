const fs = require("fs");
const path = require("path");

// ── 1. Load en.json ─────────────────────────────────────────────────────
const enPath = "apps/shared/src/i18n/messages/en.json";
const en = JSON.parse(fs.readFileSync(enPath, "utf8"));

// Collect ALL keys from en.json (with their namespace path)
const allDefinedKeys = new Map(); // key -> full path
const allDefinedKeysSet = new Set();

function collectKeys(obj, prefix) {
  for (const [key, val] of Object.entries(obj)) {
    const fullKey = prefix ? `${prefix}.${key}` : key;
    if (typeof val === "object" && val !== null && !Array.isArray(val)) {
      collectKeys(val, fullKey);
    } else {
      allDefinedKeys.set(fullKey, val);
      allDefinedKeysSet.add(fullKey);
    }
  }
}
collectKeys(en, "");
console.log(`📊 en.json has ${allDefinedKeys.size} total keys across ${Object.keys(en).length} namespaces\n`);

// ── 2. Extract all t() calls from source files ─────────────────────────
const srcDirs = [
  "apps/frontend/src",
  "apps/mobile-pwa/src",
  "apps/admin-portal/src",
  "apps/shared/src",
];

// Track the t() namespace context per file
// We need to find `const t = useTranslations("namespace")` and then map all `t("key")` calls to that namespace

const extPatterns = [".tsx", ".ts"];

function findFiles(dir) {
  const results = [];
  try {
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    for (const entry of entries) {
      const fullPath = path.join(dir, entry.name);
      if (entry.isDirectory() && !entry.name.startsWith(".") && entry.name !== "node_modules") {
        results.push(...findFiles(fullPath));
      } else if (entry.isFile() && extPatterns.some(ext => entry.name.endsWith(ext)) && entry.name !== "nul") {
        results.push(fullPath);
      }
    }
  } catch {}
  return results;
}

const allFiles = [];
for (const dir of srcDirs) {
  allFiles.push(...findFiles(dir));
}
console.log(`📁 Scanning ${allFiles.length} source files...`);

// Track all used keys with their namespace context
const usedKeys = new Map(); // "namespace.key" -> { count, files: [] }
const missingKeys = []; // keys that are used but not defined
const orphanKeys = []; // keys that are defined but never used

// For each file, find all useTranslations calls and t() calls
for (const filePath of allFiles) {
  const content = fs.readFileSync(filePath, "utf8");
  const relativePath = path.relative(process.cwd(), filePath);

  // Skip generated files
  if (content.includes("// This file is auto-generated") || content.includes("// @generated")) continue;
  if (content.includes("// Auto-generated by")) continue;

  // Find all useTranslations declarations with their namespace
  const hookRegex = /(?:const\s+(\w+)\s*=\s*useTranslations\s*\(|let\s+(\w+)\s*=\s*useTranslations\s*\()\s*["']([^"']+)["']\s*\)/g;
  let match;
  while ((match = hookRegex.exec(content)) !== null) {
    const varName = match[1] || match[2];
    const namespace = match[3];

    // Now find all t("key") calls using this variable name
    // Match patterns like t("key"), t('key'), t(`key`), t("key", { ... })
    const tCallRegex = new RegExp(`${varName}\\s*\\(\\s*["\`]([^"\`]+)["\`]`, "g");
    let tMatch;
    while ((tMatch = tCallRegex.exec(content)) !== null) {
      const key = tMatch[1];
      // Skip template literals with interpolation
      if (key.includes("${")) continue;
      // Skip keys that look like CSS class names or numeric
      if (/^\d+$/.test(key)) continue;

      const fullKey = namespace ? `${namespace}.${key}` : key;

      if (!usedKeys.has(fullKey)) {
        usedKeys.set(fullKey, { count: 0, files: [] });
      }
      const entry = usedKeys.get(fullKey);
      entry.count++;
      if (!entry.files.includes(relativePath)) {
        entry.files.push(relativePath);
      }

      // Check if this key exists in en.json
      // Split by dots to traverse the namespace
      const parts = fullKey.split(".");
      let current = en;
      let found = true;
      for (const p of parts) {
        if (current && typeof current === "object" && p in current) {
          current = current[p];
        } else {
          found = false;
          break;
        }
      }

      if (!found) {
        // But check if it's a leaf string value
        if (typeof current !== "string" && current !== undefined) {
          // The key resolved but to an object, not a string - likely wrong key
          missingKeys.push({ key: fullKey, file: relativePath, reason: "resolves to object, not string" });
        } else if (!found) {
          missingKeys.push({ key: fullKey, file: relativePath, reason: "key not found" });
        }
      } else if (typeof current !== "string") {
        missingKeys.push({ key: fullKey, file: relativePath, reason: "resolves to object, not string" });
      }
    }
  }
}

// ── 3. Find orphan keys (defined but never used) ──────────────────────
for (const [fullKey] of allDefinedKeys) {
  // Check if any namespace variant of this key is used
  const parts = fullKey.split(".");
  const keyName = parts[parts.length - 1];
  const parentNs = parts.slice(0, -1).join(".");

  // Check if used with its exact namespace
  const usedKey = usedKeys.get(fullKey);

  if (!usedKey) {
    // Maybe used with a different namespace but same key name
    let foundAnywhere = false;
    for (const [usedFullKey] of usedKeys) {
      const usedParts = usedFullKey.split(".");
      const usedKeyName = usedParts[usedParts.length - 1];
      if (usedKeyName === keyName && usedFullKey !== fullKey) {
        foundAnywhere = true;
        break;
      }
    }

    if (!foundAnywhere) {
      orphanKeys.push({ key: fullKey, value: allDefinedKeys.get(fullKey) });
    }
  }
}

// ── 4. Report results ─────────────────────────────────────────────────
console.log(`\n🔴 MISSING KEYS (used in t() but not in en.json): ${missingKeys.length}`);
if (missingKeys.length > 0) {
  // Group by file
  const byFile = {};
  for (const mk of missingKeys) {
    if (!byFile[mk.file]) byFile[mk.file] = [];
    byFile[mk.file].push(mk);
  }
  for (const [file, keys] of Object.entries(byFile).sort()) {
    console.log(`  📄 ${file}`);
    for (const k of keys) {
      console.log(`    ❌ ${k.key} — ${k.reason}`);
    }
  }
}

console.log(`\n🗑️ ORPHAN KEYS (defined in en.json but never called in any t()): ${orphanKeys.length}`);
if (orphanKeys.length > 0) {
  const byNs = {};
  for (const ok of orphanKeys) {
    const ns = ok.key.split(".")[0];
    if (!byNs[ns]) byNs[ns] = [];
    byNs[ns].push(ok);
  }
  for (const [ns, keys] of Object.entries(byNs)) {
    console.log(`  📦 ${ns}: ${keys.length} orphans`);
    for (const k of keys.slice(0, 5)) {
      console.log(`    💤 ${k.key} = "${k.value?.substring(0, 40)}..."`);
    }
    if (keys.length > 5) console.log(`    ... and ${keys.length - 5} more`);
  }
}

// ── 5. Check for namespace mismatches ─────────────────────────────────
// Where a key is used with a different namespace than where it's defined
console.log(`\n🔍 USED KEYS by namespace:`);
const byNsUsed = {};
for (const [fullKey, info] of usedKeys) {
  const ns = fullKey.split(".")[0];
  if (!byNsUsed[ns]) byNsUsed[ns] = [];
  byNsUsed[ns].push(fullKey);
}
for (const [ns, keys] of Object.entries(byNsUsed).sort()) {
  console.log(`  ${ns}: ${keys.length} keys used across ${new Set(keys.map(k => usedKeys.get(k).files).flat()).size} files`);
}

// ── 6. Summary ────────────────────────────────────────────────────────
console.log(`\n${'='.repeat(60)}`);
console.log(`📋 AUDIT SUMMARY`);
console.log(`${'='.repeat(60)}`);
console.log(`Total en.json keys:    ${allDefinedKeys.size}`);
console.log(`Total t() calls found: ${usedKeys.size}`);
console.log(`Missing keys:          ${missingKeys.length}`);
console.log(`Orphan keys:           ${orphanKeys.length}`);

// Print just the missing key names for easy action
if (missingKeys.length > 0) {
  console.log(`\n🎯 ALL MISSING KEYS (add these to en.json):`);
  const uniqueMissing = [...new Set(missingKeys.map(mk => mk.key))];
  for (const key of uniqueMissing) {
    console.log(`  ${key}`);
  }
}
