// ── Validation helpers ──────────────────────────────────────────────────
function extractParams(str) {
  if (typeof str !== "string") return [];
  return [...str.matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort();
}

function validateLocale(locale, data, en) {
  const errors = [];
  const warnings = [];

  // 1. JSON roundtrip
  try { JSON.parse(JSON.stringify(data)); }
  catch (e) { errors.push(`JSON parse failed: ${e.message}`); return { errors, warnings }; }

  // 2. Interpolation param check
  function checkParams(enObj, locObj, prefix = "") {
    for (const [key, val] of Object.entries(enObj)) {
      const fullKey = prefix ? `${prefix}.${key}` : key;
      if (typeof val === "object" && val !== null) {
        if (locObj && typeof locObj === "object") checkParams(val, locObj[key], fullKey);
        continue;
      }
      if (typeof val !== "string") continue;
      const locVal = locObj?.[key];
      if (typeof locVal !== "string") continue;
      const enParams = extractParams(val);
      const locParams = extractParams(locVal);
      const missing = enParams.filter((p) => !locParams.includes(p));
      if (missing.length > 0) {
        errors.push(`${fullKey}: MISSING params [${missing.join(", ")}] (English: [${enParams.join(", ")}])`);
      }
      // Check for HTML error pages in SVGs
      if (locVal.includes("<!DOCTYPE html>") || locVal.includes("Wikimedia Error")) {
        errors.push(`${fullKey}: contains HTML error page instead of translation!`);
      }
    }
  }
  checkParams(en, data);

  return { errors, warnings };
}

