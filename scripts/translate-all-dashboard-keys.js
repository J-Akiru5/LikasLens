async function main() {
  const args = process.argv.slice(2);
  const dryRun = !args.includes("--apply");
  const localeArg = args.includes("--locale") ? args[args.indexOf("--locale") + 1] : null;

  console.log("=== Comprehensive Dashboard Translation ===");
  console.log(`Mode: ${dryRun ? "DRY RUN" : "APPLY"}`);
  console.log("");

  const en = JSON.parse(fs.readFileSync(path.join(SHARED_DIR, "en.json"), "utf8"));
  const dashEn = en.dashboard || {};
  const enKeys = Object.keys(dashEn);
  console.log(`English dashboard keys: ${enKeys.length}`);

  const locales = localeArg ? [localeArg] : ["fil", "vi", "id", "ms", "ta", "th", "km", "my", "lo"];

  for (const loc of locales) {
    const dict = DICT[loc] || {};
    const fp = path.join(SHARED_DIR, `${loc}.json`);
    if (!fs.existsSync(fp)) { console.log(`⚠️  ${fp} not found`); continue; }

    const localeData = JSON.parse(fs.readFileSync(fp, "utf8"));
    if (!localeData.dashboard) localeData.dashboard = {};
    const dash = localeData.dashboard;

    let dictApplied = 0;
    let apiTranslated = 0;
    let skipped = 0;
    let skippedTechnical = 0;

    // Find keys still in English
    const keysToTranslate = [];
    for (const key of enKeys) {
      const enVal = dashEn[key];
      if (!enVal || typeof enVal !== "string" || enVal.length < 3) continue;
      if (dash[key] !== enVal) { skipped++; continue; } // already translated

      // Check if it's a technical term that stays the same
      const lookupKey = KEY_TO_DICT[key] || enVal;
      if (SAME_IN_ALL.has(enVal) || SAME_IN_ALL.has(lookupKey)) {
        skippedTechnical++;
        continue;
      }

      // Check dictionary first
      if (dict[enVal]) {
        dash[key] = dict[enVal];
        dictApplied++;
      } else {
        keysToTranslate.push({ key, enVal, lookupKey });
      }
    }

    // Use MyMemory API for remaining keys (longer phrases only)
    const myLang = LOCALE_MAP[loc];
    for (const { key, enVal, lookupKey } of keysToTranslate) {
      // Only use API for strings > 5 chars to avoid same-text returns
      if (enVal.length <= 5) {
        skipped++;
        continue;
      }

      // Skip if it looks like a brand/technical term
      if (/^[A-Z][a-z]+(\s+[A-Z][a-z]+)*$/.test(enVal) && enVal.split(" ").length <= 2) {
        // Short proper nouns - keep as-is
        skipped++;
        continue;
      }

      const params = extractParams(enVal);
      let textToTranslate = enVal;
      const paramMap = {};
      params.forEach((p, i) => {
        const marker = `XPARAM${i}X`;
        paramMap[marker] = `{${p}}`;
        textToTranslate = textToTranslate.replace(`{${p}}`, marker);
      });

      const translatedText = await translateText(textToTranslate, "en", myLang);
      if (translatedText && translatedText.toLowerCase() !== enVal.toLowerCase()) {
        let finalText = translatedText;
        for (const [marker, original] of Object.entries(paramMap)) {
          finalText = finalText.replace(new RegExp(marker, "gi"), original);
        }
        dash[key] = finalText;
        apiTranslated++;
      } else {
        skipped++;
      }

      // Save periodically
      if ((dictApplied + apiTranslated) % 10 === 0 && (dictApplied + apiTranslated) > 0) {
        if (!dryRun) {
          localeData.dashboard = dash;
          fs.writeFileSync(fp, JSON.stringify(localeData, null, 2) + "\n", "utf8");
        }
      }

      // Rate limit: 3s between API calls
      await new Promise(r => setTimeout(r, 3000));
    }

    // Final save
    if (!dryRun && (dictApplied + apiTranslated) > 0) {
      localeData.dashboard = dash;
      fs.writeFileSync(fp, JSON.stringify(localeData, null, 2) + "\n", "utf8");
    }

    const stillEnglish = enKeys.filter(k =>
      typeof dashEn[k] === "string" && dashEn[k].length > 3 && dash[k] === dashEn[k]
    ).length;

    console.log(`${loc}: dict=${dictApplied} api=${apiTranslated} technical=${skippedTechnical} skipped=${skipped} remaining=${stillEnglish}`);
  }

  console.log(dryRun ? "\n=== DRY RUN COMPLETE ===" : "\n=== TRANSLATIONS APPLIED ===");
}

