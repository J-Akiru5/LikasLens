// Helper: check if English value matches (used to detect untranslated)
function isStillEnglish(enVal, localeVal) {
  if (typeof localeVal !== 'string') return false;
  if (localeVal === enVal && enVal.length > 3) return true;
  return false;
}

// Main function
async function main() {
  const args = process.argv.slice(2);
  const dryRun = !args.includes('--apply');
  const localeFilter = args.find(a => args.indexOf(a) === args.indexOf('--locale') + 1);
  
  console.log('=== Dictionary-based Dashboard Translation ===');
  console.log(`Mode: ${dryRun ? 'DRY RUN (use --apply to apply)' : 'APPLY'}`);
  console.log('');
  
  // Load English dashboard keys
  const enPath = path.join(SHARED_DIR, 'en.json');
  const enData = JSON.parse(fs.readFileSync(enPath, 'utf8'));
  const dashEn = enData.dashboard || {};
  const enKeys = Object.keys(dashEn);
  
  console.log(`English dashboard keys: ${enKeys.length}`);
  console.log('');
  
  const locales = ['fil', 'vi', 'id', 'ms', 'ta', 'th', 'km', 'my', 'lo'];
  const targetLocales = localeFilter ? [localeFilter] : locales;
  
  for (const loc of targetLocales) {
    const fp = path.join(SHARED_DIR, `${loc}.json`);
    const data = JSON.parse(fs.readFileSync(fp, 'utf8'));
    const dash = data.dashboard || {};
    const dict = DICTIONARIES[loc] || {};
    
    let translated = 0;
    let skipped = 0;
    let dictApplied = 0;
    
    for (const key of enKeys) {
      if (isStillEnglish(dashEn[key], dash[key])) {
        // Try dictionary first
        if (dict[dashEn[key]]) {
          dash[key] = dict[dashEn[key]];
          dictApplied++;
          translated++;
        } else {
          skipped++;
        }
      } else {
        skipped++;
      }
    }
    
    if (!dryRun && dictApplied > 0) {
      data.dashboard = dash;
      fs.writeFileSync(fp, JSON.stringify(data, null, 2), 'utf8');
    }
    
    const remaining = enKeys.filter(k => isStillEnglish(dashEn[k], dash[k])).length;
    console.log(`${loc}: dictApplied=${dictApplied}, stillEnglish=${remaining}, total=${enKeys.length}`);
  }
  
  console.log('');
  console.log(dryRun ? '=== DRY RUN COMPLETE ===' : '=== TRANSLATIONS APPLIED ===');
}

main().catch(console.error);
