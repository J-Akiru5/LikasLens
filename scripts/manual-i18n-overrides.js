// ── Main logic ──────────────────────────────────────────────────────────

const args = process.argv.slice(2);
const applyMode = args.includes("--apply");
const allMode = args.includes("--all");
const localeArg = args.indexOf("--locale") !== -1 ? args[args.indexOf("--locale") + 1] : null;

if (!applyMode) {
  console.log("Usage: node scripts/manual-i18n-overrides.js --apply --locale <code> | --all");
  console.log("Available locales: fil, vi, id, ms, ta, th, km, my, lo");
  process.exit(0);
}

const locales = allMode ? Object.keys(OVERRIDES) : [localeArg];
if (!allMode && !localeArg) {
  console.error("Error: specify --locale <code> or --all");
  process.exit(1);
}

const enPath = path.join(MESSAGES_DIR, "en.json");
const en = JSON.parse(fs.readFileSync(enPath, "utf8"));
const dashEn = en.dashboard || {};

for (const locale of locales) {
  if (!OVERRIDES[locale]) {
    console.log(`⚠ No overrides defined for ${locale}, skipping`);
    continue;
  }

  const overrides = OVERRIDES[locale];
  const fp = path.join(MESSAGES_DIR, `${locale}.json`);
  if (!fs.existsSync(fp)) {
    console.log(`⚠ File not found: ${fp}, skipping`);
    continue;
  }

  const data = JSON.parse(fs.readFileSync(fp, "utf8"));
  if (!data.dashboard) data.dashboard = {};

  let applied = 0;
  let alreadyCorrect = 0;
  let skipped = 0;

  for (const [key, val] of Object.entries(overrides)) {
    if (!dashEn[key]) {
      skipped++;
      continue; // key doesn't exist in English source
    }
    if (data.dashboard[key] === val) {
      alreadyCorrect++;
      continue; // already has this value
    }
    data.dashboard[key] = val;
    applied++;
  }

  // Validate JSON + interpolation params before writing
  const validation = validateLocale(locale, data, en);
  if (validation.errors.length > 0) {
    console.error(`❌ Validation failed for ${locale}:`);
    for (const err of validation.errors) console.error(`   ${err}`);
    continue;
  }

  fs.writeFileSync(fp, JSON.stringify(data, null, 2) + "\n", "utf8");

  // Also write to frontend and mobile-pwa
  const feDir = path.join(__dirname, "..", "apps", "frontend", "src", "i18n", "messages");
  const mpDir = path.join(__dirname, "..", "apps", "mobile-pwa", "src", "i18n", "messages");

  for (const dir of [feDir, mpDir]) {
    const target = path.join(dir, `${locale}.json`);
    if (fs.existsSync(target)) {
      fs.writeFileSync(target, JSON.stringify(data, null, 2) + "\n", "utf8");
    }
  }

  // Count remaining untranslated
  const db = data.dashboard || {};
  let remaining = 0;
  for (const k of Object.keys(dashEn)) {
    if (typeof db[k] === "string" && db[k] === dashEn[k] && dashEn[k].length > 3) remaining++;
  }

  console.log(`✅ ${locale}: applied=${applied} alreadyCorrect=${alreadyCorrect} skipped=${skipped} remaining=${remaining}`);
}
