function extractParams(str) { return [...str.matchAll(/\{(\w+)\}/g)].map(m => m[1]).sort(); }

async function translateText(text, from, to) {
  const url = `https://api.mymemory.translated.net/get?q=${encodeURIComponent(text)}&langpair=${from}|${to}&de=likaslens-i18n@translation.local`;
  try {
    const res = await fetch(url);
    if (res.status === 429) {
      console.log("    ⏳ Rate limited, waiting 60s...");
      await new Promise(r => setTimeout(r, 60000));
      return translateText(text, from, to);
    }
    if (!res.ok) return null;
    const data = await res.json();
    if (data.responseStatus === 200 && data.responseData?.translatedText) {
      let t = data.responseData.translatedText;
      if (t === t.toUpperCase() && text !== text.toUpperCase() && text.length > 4) {
        t = t.charAt(0).toUpperCase() + t.slice(1).toLowerCase();
      }
      return t;
    }
    return null;
  } catch (err) {
    console.log(`    ❌ ${err.message}`);
    return null;
  }
}

