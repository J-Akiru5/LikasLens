function findFiles(dir) {
  const r = [];
  try {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const fp = path.join(dir, e.name);
      if (e.isDirectory() && !e.name.startsWith(".") && e.name !== "node_modules") r.push(...findFiles(fp));
      else if (e.isFile() && (e.name.endsWith(".tsx") || e.name.endsWith(".ts")) && e.name !== "nul") r.push(fp);
    }
  } catch {}
  return r;
}

